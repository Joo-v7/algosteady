CREATE TABLE exercise_content (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
  , exercise_id VARCHAR(255) NOT NULL
  , content_version VARCHAR(255) NOT NULL
  , snapshot JSONB NOT NULL
  , created_at TIMESTAMP WITH TIME ZONE NOT NULL
  , UNIQUE (exercise_id, content_version)
);

CREATE TABLE execution_job (
    id UUID PRIMARY KEY
  , exercise_id VARCHAR(255) NOT NULL
  , content_version VARCHAR(255) NOT NULL
  , language VARCHAR(255) NOT NULL
  , code TEXT NOT NULL
  , example_id VARCHAR(255) NOT NULL
  , status VARCHAR(255) NOT NULL CHECK (status IN ('QUEUED', 'RUNNING', 'COMPLETED', 'FAILED'))
  , queued_at TIMESTAMP WITH TIME ZONE NOT NULL
  , started_at TIMESTAMP WITH TIME ZONE
  , completed_at TIMESTAMP WITH TIME ZONE
  , preparation JSONB
  , message TEXT
  , FOREIGN KEY (exercise_id, content_version) REFERENCES exercise_content (exercise_id, content_version)
);
CREATE INDEX execution_job_queue ON execution_job (status, queued_at);

CREATE TABLE execution_test_result (
    id UUID PRIMARY KEY
  , job_id UUID NOT NULL REFERENCES execution_job (id)
  , test_id VARCHAR(255) NOT NULL
  , result JSONB NOT NULL
  , passed BOOLEAN NOT NULL
  , UNIQUE (job_id, test_id)
);
