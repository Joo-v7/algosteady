-- 회원 테이블 생성
CREATE TABLE member_account (
    id UUID PRIMARY KEY
  , provider VARCHAR(255) NOT NULL
  , provider_subject VARCHAR(255) NOT NULL
  , email VARCHAR(255)
  , name VARCHAR(255)
  , created_at TIMESTAMP WITH TIME ZONE NOT NULL
  , last_login_at TIMESTAMP WITH TIME ZONE NOT NULL
  , UNIQUE (provider, provider_subject)
);

COMMENT ON TABLE member_account IS '회원';
COMMENT ON COLUMN member_account.id IS '회원 ID';
COMMENT ON COLUMN member_account.provider IS 'OAuth 제공자 코드';
COMMENT ON COLUMN member_account.provider_subject IS 'OAuth 제공자 사용자 식별자';
COMMENT ON COLUMN member_account.email IS '이메일';
COMMENT ON COLUMN member_account.name IS '이름';
COMMENT ON COLUMN member_account.created_at IS '회원 등록 시각';
COMMENT ON COLUMN member_account.last_login_at IS '마지막 로그인 시각';

-- 학습 분류 테이블 생성
CREATE TABLE exercise_category (
    id VARCHAR(255) PRIMARY KEY
  , label VARCHAR(255) NOT NULL
  , display_order INTEGER NOT NULL UNIQUE
);

COMMENT ON TABLE exercise_category IS '학습 분류';
COMMENT ON COLUMN exercise_category.id IS '학습 분류 ID';
COMMENT ON COLUMN exercise_category.label IS '학습 분류명';
COMMENT ON COLUMN exercise_category.display_order IS '표시 순서';

-- 학습 분류와 콘텐츠 분류 연결 테이블 생성
CREATE TABLE exercise_category_member (
    category_id VARCHAR(255) NOT NULL REFERENCES exercise_category (id)
  , content_category VARCHAR(255) PRIMARY KEY
);

COMMENT ON TABLE exercise_category_member IS '학습 분류와 콘텐츠 분류 연결';
COMMENT ON COLUMN exercise_category_member.category_id IS '학습 분류 ID';
COMMENT ON COLUMN exercise_category_member.content_category IS '콘텐츠 분류 코드';

-- 버전별 학습 콘텐츠 테이블 생성
CREATE TABLE exercise_content (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
  , exercise_id VARCHAR(255) NOT NULL
  , content_version VARCHAR(255) NOT NULL
  , snapshot JSONB NOT NULL
  , created_at TIMESTAMP WITH TIME ZONE NOT NULL
  , UNIQUE (exercise_id, content_version)
);

COMMENT ON TABLE exercise_content IS '버전별 학습 콘텐츠';
COMMENT ON COLUMN exercise_content.id IS '콘텐츠 ID';
COMMENT ON COLUMN exercise_content.exercise_id IS '학습 ID';
COMMENT ON COLUMN exercise_content.content_version IS '콘텐츠 버전';
COMMENT ON COLUMN exercise_content.snapshot IS '학습 콘텐츠 스냅샷';
COMMENT ON COLUMN exercise_content.created_at IS '콘텐츠 등록 시각';

-- 실행·채점 작업 테이블 생성
CREATE TABLE execution_job (
    id UUID PRIMARY KEY
  , member_id UUID REFERENCES member_account (id) ON DELETE CASCADE
  , exercise_id VARCHAR(255) NOT NULL
  , content_version VARCHAR(255) NOT NULL
  , language VARCHAR(255) NOT NULL
  , code TEXT NOT NULL
  , example_id VARCHAR(255)
  , kind VARCHAR(255) NOT NULL DEFAULT 'RUN'
  , status VARCHAR(255) NOT NULL CHECK (status IN ('QUEUED', 'RUNNING', 'COMPLETED', 'FAILED'))
  , queued_at TIMESTAMP WITH TIME ZONE NOT NULL
  , started_at TIMESTAMP WITH TIME ZONE
  , completed_at TIMESTAMP WITH TIME ZONE
  , preparation JSONB
  , message TEXT
  , CONSTRAINT execution_job_kind CHECK (kind IN ('RUN', 'GRADING'))
  , CONSTRAINT execution_job_example CHECK (
        (kind = 'RUN' AND example_id IS NOT NULL) OR (kind = 'GRADING' AND example_id IS NULL)
    )
  , FOREIGN KEY (exercise_id, content_version) REFERENCES exercise_content (exercise_id, content_version)
);
CREATE INDEX execution_job_queue ON execution_job (status, queued_at);

COMMENT ON TABLE execution_job IS '실행·채점 작업';
COMMENT ON COLUMN execution_job.id IS '작업 ID';
COMMENT ON COLUMN execution_job.member_id IS '작업 소유 회원 ID';
COMMENT ON COLUMN execution_job.exercise_id IS '학습 ID';
COMMENT ON COLUMN execution_job.content_version IS '콘텐츠 버전';
COMMENT ON COLUMN execution_job.language IS '실행 언어 코드';
COMMENT ON COLUMN execution_job.code IS '실행 원본 코드';
COMMENT ON COLUMN execution_job.example_id IS '실행 예제 ID';
COMMENT ON COLUMN execution_job.kind IS '작업 유형';
COMMENT ON COLUMN execution_job.status IS '작업 상태';
COMMENT ON COLUMN execution_job.queued_at IS '작업 접수 시각';
COMMENT ON COLUMN execution_job.started_at IS '작업 시작 시각';
COMMENT ON COLUMN execution_job.completed_at IS '작업 종료 시각';
COMMENT ON COLUMN execution_job.preparation IS '컴파일 결과';
COMMENT ON COLUMN execution_job.message IS '작업 장애·중단 사유';

-- 테스트 실행 결과 테이블 생성
CREATE TABLE execution_test_result (
    id UUID PRIMARY KEY
  , job_id UUID NOT NULL REFERENCES execution_job (id) ON DELETE CASCADE
  , test_id VARCHAR(255) NOT NULL
  , result JSONB NOT NULL
  , passed BOOLEAN NOT NULL
  , UNIQUE (job_id, test_id)
);

COMMENT ON TABLE execution_test_result IS '테스트 실행 결과';
COMMENT ON COLUMN execution_test_result.id IS '테스트 결과 ID';
COMMENT ON COLUMN execution_test_result.job_id IS '작업 ID';
COMMENT ON COLUMN execution_test_result.test_id IS '테스트 ID';
COMMENT ON COLUMN execution_test_result.result IS '테스트 실행 결과';
COMMENT ON COLUMN execution_test_result.passed IS '테스트 통과 여부';

-- 제출 기록 테이블 생성
CREATE TABLE submission (
    id UUID PRIMARY KEY
  , member_id UUID REFERENCES member_account (id) ON DELETE CASCADE
  , exercise_id VARCHAR(255) NOT NULL
  , content_version VARCHAR(255) NOT NULL
  , language VARCHAR(255) NOT NULL
  , code TEXT NOT NULL
  , reference_viewed BOOLEAN NOT NULL
  , job_id UUID NOT NULL UNIQUE REFERENCES execution_job (id) ON DELETE CASCADE
  , submitted_at TIMESTAMP WITH TIME ZONE NOT NULL
  , FOREIGN KEY (exercise_id, content_version) REFERENCES exercise_content (exercise_id, content_version)
);
CREATE INDEX submission_member_history
    ON submission (member_id, exercise_id, language, submitted_at DESC, id DESC);

COMMENT ON TABLE submission IS '제출 기록';
COMMENT ON COLUMN submission.id IS '제출 ID';
COMMENT ON COLUMN submission.member_id IS '제출 회원 ID';
COMMENT ON COLUMN submission.exercise_id IS '학습 ID';
COMMENT ON COLUMN submission.content_version IS '콘텐츠 버전';
COMMENT ON COLUMN submission.language IS '제출 언어 코드';
COMMENT ON COLUMN submission.code IS '제출 코드';
COMMENT ON COLUMN submission.reference_viewed IS '기준 코드 열람 여부';
COMMENT ON COLUMN submission.job_id IS '채점 작업 ID';
COMMENT ON COLUMN submission.submitted_at IS '제출 접수 시각';

-- 일일 학습 배정 테이블 생성
CREATE TABLE daily_learning (
    learning_date DATE PRIMARY KEY
  , exercise_id VARCHAR(255) NOT NULL
  , created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

COMMENT ON TABLE daily_learning IS '일일 학습 배정';
COMMENT ON COLUMN daily_learning.learning_date IS '학습 날짜';
COMMENT ON COLUMN daily_learning.exercise_id IS '배정 학습 ID';
COMMENT ON COLUMN daily_learning.created_at IS '배정 생성 시각';

-- 회원별 일일 학습 완료 테이블 생성
CREATE TABLE daily_learning_completion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
  , member_id UUID NOT NULL REFERENCES member_account (id) ON DELETE CASCADE
  , learning_date DATE NOT NULL REFERENCES daily_learning (learning_date)
  , job_id UUID NOT NULL REFERENCES execution_job (id) ON DELETE CASCADE
  , completed_at TIMESTAMP WITH TIME ZONE NOT NULL
  , UNIQUE (member_id, learning_date)
);

COMMENT ON TABLE daily_learning_completion IS '회원별 일일 학습 완료';
COMMENT ON COLUMN daily_learning_completion.id IS '학습 완료 ID';
COMMENT ON COLUMN daily_learning_completion.member_id IS '완료 회원 ID';
COMMENT ON COLUMN daily_learning_completion.learning_date IS '학습 날짜';
COMMENT ON COLUMN daily_learning_completion.job_id IS '완료 인정 채점 작업 ID';
COMMENT ON COLUMN daily_learning_completion.completed_at IS '채점 완료 시각';

