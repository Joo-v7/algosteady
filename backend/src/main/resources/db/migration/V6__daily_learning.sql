CREATE TABLE daily_learning (
    learning_date DATE PRIMARY KEY
  , exercise_id VARCHAR(255) NOT NULL
  , created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE daily_learning_completion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
  , member_id UUID NOT NULL REFERENCES member_account (id)
  , learning_date DATE NOT NULL REFERENCES daily_learning (learning_date)
  , job_id UUID NOT NULL REFERENCES execution_job (id)
  , completed_at TIMESTAMP WITH TIME ZONE NOT NULL
  , UNIQUE (member_id, learning_date)
);
